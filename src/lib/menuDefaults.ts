export function normalizeBundledAssetPath(src?: string | null): string {
  if (!src || typeof src !== 'string') {
    return startersBruschettaImg;
  }
  const trimmed = src.trim();
  if (!trimmed) {
    return startersBruschettaImg;
  }
  for (const matcher of BUNDLED_IMAGE_MATCHERS) {
    if (trimmed.includes(matcher.token)) {
      return matcher.asset;
    }
  }
  return trimmed;
}

